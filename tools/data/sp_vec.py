# Sykes-Picot 1916 (+ zona Rusia 1916 & Italia 1917) sebagai poligon tangan, dipotong ke daratan Utsmani.
import json
from shapely.geometry import shape, mapping, Polygon, box
from shapely.ops import unary_union

C = {f['properties']['a3']: shape(f['geometry']) for f in json.load(open('build/reg_countries.json'))['features']}
land = unary_union([C[a] for a in ['TUR', 'SYR', 'LBN', 'ISR', 'PSX', 'JOR', 'IRQ', 'SAU', 'KWT']]).buffer(0)

# garis-garis bersama (lon, lat)
BLUE_E = [(35.55, 33.15), (35.9, 33.4), (36.1, 33.85), (36.45, 34.45), (36.55, 34.95), (36.5, 35.45), (36.65, 35.95), (36.9, 36.45),
          (37.8, 36.75), (39.0, 36.85), (40.2, 37.0), (41.2, 37.25), (41.6, 37.7), (41.5, 38.3)]
RU_W = [(41.5, 38.3), (40.3, 38.6), (39.8, 39.2), (39.5, 40.0)]
BLUE_N = [(39.5, 40.0), (38.5, 40.2), (37.3, 40.1), (36.4, 39.5), (35.6, 38.6), (34.8, 38.0), (33.9, 37.4), (33.2, 36.9)]
RU_S = [(41.5, 38.3), (42.6, 38.0), (43.6, 37.75), (44.6, 37.6)]
AB = [(35.62, 32.7), (36.3, 32.45), (37.5, 32.7), (39.0, 33.3), (40.6, 33.95), (42.0, 34.3), (43.6, 34.6), (44.6, 35.1), (45.6, 35.0), (46.8, 35.0)]
B_S = [(34.95, 29.5), (36.0, 30.1), (36.8, 30.6), (38.0, 31.3), (39.5, 31.6), (41.0, 31.3), (42.5, 30.6), (44.0, 29.6), (45.5, 28.9), (46.8, 28.3), (48.5, 27.6), (50.5, 27.6)]

P = lambda pts: Polygon(pts).buffer(0)
haifa = P([(34.9, 32.75), (35.15, 32.75), (35.15, 32.98), (34.9, 32.98)])
intl = P([(33.8, 33.15), (35.55, 33.15), (35.62, 32.85), (35.62, 32.7), (35.57, 32.3), (35.55, 31.8), (35.47, 31.4), (34.3, 31.33), (33.8, 31.4)])
blue = P([(34.4, 33.15)] + BLUE_E + RU_W + BLUE_N + [(33.0, 36.0), (34.4, 34.2)])
ru = P([(38.8, 41.8), (38.8, 40.9)] + RU_W[::-1] + RU_S[1:] + [(45.5, 39.5), (43.0, 42.0), (41.0, 42.2)])
straits = P([(26.0, 40.6), (27.3, 41.0), (28.1, 41.7), (29.95, 41.35), (30.2, 40.8), (29.0, 40.45), (27.4, 40.25), (26.4, 39.95), (26.0, 40.2)])
it_c = P([(26.0, 36.3), (26.4, 38.3), (27.5, 38.9), (29.0, 39.2), (31.0, 39.2), (32.6, 38.9), (33.8, 38.3), (34.8, 38.0), (33.9, 37.4), (33.2, 36.9), (33.0, 35.8)])
it_i = P([(25.8, 38.3), (26.4, 38.3), (27.5, 38.9), (29.0, 39.2), (31.0, 39.2), (32.6, 38.9), (33.8, 38.3), (34.8, 38.0), (35.6, 38.6),
          (34.0, 39.3), (32.5, 39.9), (30.5, 40.1), (28.5, 40.0), (26.8, 39.75), (25.8, 39.5)])
red = P([(43.3, 33.7), (44.0, 34.3), (45.2, 34.6), (46.5, 34.0), (49.5, 30.0), (48.6, 28.4), (47.9, 28.5), (47.5, 29.6), (47.2, 30.4),
         (46.3, 31.0), (45.3, 31.7), (44.3, 32.4), (43.6, 33.1)])
A = P([(35.55, 33.15)] + BLUE_E[1:] + RU_S[1:] + [(46.8, 37.6)] + AB[::-1] + [(35.62, 32.85)])
B = P([(35.62, 32.85)] + AB + [(50.5, 31.0)] + B_S[::-1] + [(34.2, 31.2), (34.3, 31.33), (35.47, 31.4)])

out, taken = [], None
def add(k, g):
    global taken
    g = g.intersection(land)
    if taken is not None: g = g.difference(taken)
    g = g.buffer(0)
    taken = g if taken is None else unary_union([taken, g])
    out.append({'type': 'Feature', 'properties': {'k': k}, 'geometry': mapping(g)})
    print(k, round(g.area, 3))
add('red_br', unary_union([haifa, red]))
add('intl', intl)
add('blue_fr', blue)
add('ru', unary_union([ru, straits]))
add('it_c', it_c)
add('it_i', it_i)
add('A_fr', A)
add('B_br', B)
json.dump({'type': 'FeatureCollection', 'features': out}, open('build/sp1916.json', 'w'))
